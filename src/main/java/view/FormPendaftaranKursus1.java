    // Menghitung biaya dasar sesuai kursus yang dipilih.
    private double hitungBiayaDasar(String kursus) {
        switch (kursus) {
            case "Java Desktop": return 500000;
            case "Data Science": return 650000;
            case "Web Programming": return 450000;
            case "UI/UX Design": return 400000;
            default: return 0;
        }

    }
 // Biaya fasilitas tambahan.
    private double hitungBiayaFasilitas() {
        
    double total = 0;

    if (chkModulCetak.isSelected()) {
        total += 50000;
    }

    if (chkSertifikat.isSelected()) {
        total += 75000;
    }

    if (chkAksesRekaman.isSelected()) {
        total += 100000;
    }

    return total;

    }

    // Daftar fasilitas yang dipilih.
    private String buatRingkasanFasilitas() {
       
    StringBuilder hasil = new StringBuilder();

    if (chkModulCetak.isSelected()) {
        hasil.append("- Modul Cetak\n");
    }

    if (chkSertifikat.isSelected()) {
        hasil.append("- Sertifikat\n");
    }

    if (chkAksesRekaman.isSelected()) {
        hasil.append("- Akses Rekaman\n");
    }

    if (hasil.length() == 0) {
        hasil.append("- Tidak ada fasilitas tambahan\n");
    }

    return hasil.toString();
}

        // Format angka dalam rupiah Indonesia.
    private String formatRupiah(double nilai) {
        java.text.NumberFormat format = java.text.NumberFormat.getNumberInstance(
                new java.util.Locale("id", "ID"));
        format.setMaximumFractionDigits(0);
        format.setMinimumFractionDigits(0);
        return "Rp " + format.format(nilai);
    }
        
