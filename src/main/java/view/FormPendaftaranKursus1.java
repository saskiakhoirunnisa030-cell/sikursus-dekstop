    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
     
    String namaPendaftar = txtNama.getText().trim();
    String nama = txtNama.getText().trim();
        String kode = txtKodeAkses.getText().trim();

        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama peserta wajib diisi.", "Validasi", JOptionPane.WARNING_MESSAGE);
            txtNama.requestFocusInWindow();
            return;
            
        }


        if (!kode.equals("PBO2026")) {
            lblInfoKodeAkses.setVisible(true);

            JOptionPane.showMessageDialog(
                    this,
                    "Kode akses demo salah.",
                    "Validasi",
                    JOptionPane.WARNING_MESSAGE
            );

            txtKodeAkses.requestFocusInWindow();
            return;
        }

        // Jika kode benar, sembunyikan kembali label
        lblInfoKodeAkses.setVisible(false);


        if (!rbMahasiswa.isSelected() && !rbUmum.isSelected()) {
            JOptionPane.showMessageDialog(this, "Silakan pilih jenis peserta.", "Validasi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (cmbKursus.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Silakan pilih kursus terlebih dahulu.", "Validasi", JOptionPane.WARNING_MESSAGE);
            cmbKursus.requestFocusInWindow();
            return;
        }

        String jenis = rbMahasiswa.isSelected() ? "Mahasiswa" : "Umum";
        String kursus = cmbKursus.getSelectedItem().toString();
        double biayaDasar = hitungBiayaDasar(kursus);
        double diskon = jenis.equals("Mahasiswa") ? biayaDasar * 0.10 : 0;
        double biayaFasilitas = hitungBiayaFasilitas();
        double total = biayaDasar - diskon + biayaFasilitas;

        String ringkasan = "PENDAFTARAN KURSUS\n"
                + "================================\n"
                + "Nama           : " + nama + "\n"
                + "Kode Akses     : " + kode + "\n"
                + "Jenis Peserta  : " + jenis + "\n"
                + "Kursus         : " + kursus + "\n"
                + "Biaya Dasar    : " + formatRupiah(biayaDasar) + "\n"
                + "Diskon         : " + formatRupiah(diskon) + "\n"
                + "Fasilitas:\n" + buatRingkasanFasilitas()
                + "Biaya Fasilitas: " + formatRupiah(biayaFasilitas) + "\n"
                + "================================\n"
                + "TOTAL BAYAR    : " + formatRupiah(total);

txtRingkasan.setText(ringkasan);


                                             
    }//GEN-LAST:event_btnProsesActionPerformed

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed

     int pilihan = JOptionPane.showConfirmDialog(
        this,
        "Kosongkan seluruh input?",
        "Konfirmasi Reset",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.QUESTION_MESSAGE
    );

    if (pilihan == JOptionPane.YES_OPTION) {
        txtNama.setText("");
        txtKodeAkses.setText("");

        grupJenis.clearSelection();

        cmbKursus.setSelectedIndex(0);
        chkModulCetak.setSelected(false);
        chkSertifikat.setSelected(false);
        chkAksesRekaman.setSelected(false);
        txtRingkasan.setText("");

        // Sembunyikan label informasi kode akses
        lblInfoKodeAkses.setVisible(false);

        txtNama.requestFocusInWindow();
    }
    }//GEN-LAST:event_btnResetActionPerformed

